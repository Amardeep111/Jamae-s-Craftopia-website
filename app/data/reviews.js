export function getReviewsForProduct(productId) {
  if (!productId) return SAMPLE_REVIEWS
  return SAMPLE_REVIEWS.filter((r) => r.productId === productId)
}

export function getAverageRating(reviews) {
  if (!reviews || !reviews.length) return 0
  return reviews.reduce((s, r) => s + (r.rating || 0), 0) / reviews.length
}

export function getRatingDistribution(reviews) {
  const counts = { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 }
  reviews.forEach((r) => {
    if (counts[r.rating] !== undefined) counts[r.rating]++
  })
  return counts
}
